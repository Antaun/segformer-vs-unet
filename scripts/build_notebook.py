def md(t):
    return nbf.v4.new_markdown_cell(t)


def code(t):
    return nbf.v4.new_code_cell(t)


def main() -> None:
    nb = nbf.v4.new_notebook()
    cells = [md(INTRO), md("## 1. Setup"), code(SETUP)]
    cells.append(md("## 2. Library code\nOne cell per module of the `dl_research` package, in dependency order. Run all of them once."))
    for name, title, blurb in MODULES:
        cells += [md(f"### {title}  \n{blurb}"), code(clean(name))]
    cells += [
        md("## 3. Experiment settings\nThe shared protocol is the `Config` defaults; change a value here and it applies to both models."),
        code(SETTINGS),
        md("## 4. Smoke test\nChecks the whole pipeline on synthetic data. Metrics from this are meaningless — it only proves the code runs."),
        code(SMOKE),
        md("## 5. Dataset\nExpected layout: `data/LoveDA/{Train,Val,Test}/{Urban,Rural}/images_png` (+ `masks_png` for Train/Val)."),
        code(DATASET),
        md("## 6. Learning-rate tuning (validation split only)"), code(TUNE),
        md("## 7. Full study\n2 models × 3 label fractions × 3 seeds is a long run; set `RUN_STUDY = True` deliberately."), code(STUDY),
        md("## 8. Results\nTables and figures come only from completed runs; no conclusions are written automatically."), code(AGG),
        md("## 9. Re-evaluation"), code(EVAL),
    ]
    nb.cells = cells
    nb.metadata["kernelspec"] = {"display_name": "Python 3", "language": "python", "name": "python3"}
    out = ROOT / "segformer_vs_unet.ipynb"
    nbf.write(nb, out)
    print(f"wrote {out} ({len(cells)} cells)")


if __name__ == "__main__":
    main()
