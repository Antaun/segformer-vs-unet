"""Build segformer_vs_unet.ipynb from the package source, so the notebook and the package cannot drift.

    python scripts/build_notebook.py        # rewrites segformer_vs_unet.ipynb (unexecuted)

Each module becomes one code cell with: `from __future__` and `dl_research` imports removed (everything shares one
namespace) and the argparse CLI (`def main` ... end of file) cut, since a notebook has no CLI.
"""
import ast
import re
from pathlib import Path

import nbformat as nbf

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "dl_research"

MODULES = [
    ("config", "Configuration", "Dataclass holding every setting; YAML/override handling is replaced by `build_config` below."),
    ("utils", "Utilities", "Seeding, device selection, environment info, JSON helpers."),
    ("data", "Data core", "Dataset registry, deterministic domain-stratified label-fraction subsets, augmentation, `SegDataset`, `EpochSampler`."),
    ("loveda", "LoveDA spec", "Folder layout, label mapping (raw 0 → ignore 255, raw 1–7 → classes 0–6) and a synthetic dataset generator."),
    ("metrics", "Metrics", "Confusion-matrix based mIoU, per-class IoU, F1, pixel accuracy (ignored pixels excluded)."),
    ("models", "Models", "U-Net (ResNet-50, `segmentation_models_pytorch`) and SegFormer-B2 (MiT-B2, Hugging Face)."),
    ("efficiency", "Efficiency measurement", "Parameters, GFLOPs and inference speed, measured identically for both models."),
    ("evaluate", "Evaluation", "Full-resolution evaluation, overall and per domain; `evaluate_run` re-evaluates a finished run."),
    ("train", "Training", "One (model, fraction, seed) run: AdamW + cross-entropy, resumable, writes `metrics.json`."),
    ("tune_lr", "Learning-rate tuning", "Grid search on the validation split only."),
    ("aggregate", "Aggregation", "Mean ± std over seeds, paired model gap, tables and figures."),
    ("prepare_dataset", "Dataset preparation", "Unzip and verify LoveDA, write `manifest.json`. Never downloads anything."),
]


def clean(name: str) -> str:
    text = (SRC / f"{name}.py").read_text()
    text = text.split("\ndef main(argv=None)")[0]  # drop the CLI wrapper and `if __name__ == "__main__"`
    lines = []
    for ln in text.splitlines():
        if ln.startswith("from __future__"):
            continue
        if re.match(r"\s*(from|import) dl_research", ln):
            continue
        if ln.strip() == "matplotlib.use(\"Agg\")":  # keep the notebook's inline backend
            continue
        lines.append(ln.rstrip())
    code = re.sub(r"\n{4,}", "\n\n\n", "\n".join(lines)).strip() + "\n"
    ast.parse(code)  # fail the build, not the notebook, if the cut went wrong
    return code


